  var SIGNO = ["..wwww..", ".ww..ww.", ".....ww.", "....ww..", "...ww...", "...ww...", "........", "...ww..."];

  function dentro(a, b, r) { var dx = a - 15.5, dy = b - 15.5; return dx * dx + dy * dy <= r * r; }

  /* estado: "bloqueada" | "secreta" | "ganada" | "nueva" */
  function dibujarChapa(ctx, insignia, estado) {
    ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, 32, 32);
    function px(a, b, c) { ctx.fillStyle = c; ctx.fillRect(a, b, 1, 1); }
    var apagada = estado === "bloqueada" || estado === "secreta";
    var aro = estado === "bloqueada" ? "#5a5a5a" : estado === "secreta" ? "#3a3a3a" : AROS[insignia.familia] || AROS.trivia;
    var fondo = estado === "bloqueada" ? "#262626" : estado === "secreta" ? "#1b1b1b" : insignia.familia === "secreta" ? "#1d2a44" : "#F4EFE6";
    for (var b = 0; b < 32; b++) for (var a = 0; a < 32; a++) {
      if (dentro(a, b + 1.2, 15) && !dentro(a, b, 15)) px(a, b, "#0a0a0a");
      if (dentro(a, b, 15)) px(a, b, aro);
      if (dentro(a, b, 12)) px(a, b, fondo);
    }
    if (!apagada) [[7, 6], [6, 7], [8, 5], [5, 8], [9, 4], [4, 9]].forEach(function (q) { px(q[0], q[1], "rgba(255,255,255,.75)"); });
    if (estado === "secreta") {
      SIGNO.forEach(function (fila, y) { for (var x = 0; x < 8; x++) if (fila[x] === "w") px(12 + x, 12 + y, "#FFD23F"); });
      return;
    }
    (ICONOS[insignia.icono] || []).forEach(function (fila, y) {
      for (var x = 0; x < 16; x++) {
        var c = PALETA[fila[x]];
        if (c) px(8 + x, 8 + y, estado === "bloqueada" ? "#4a4a4a" : c);
      }
    });
    if (estado === "nueva") [[1, 3], [2, 2], [3, 1], [28, 4], [29, 3], [30, 2], [27, 29], [28, 28], [3, 28]].forEach(function (q) { px(q[0], q[1], "#FFD23F"); });
  }

