const mark = (rows, w, pos, kind) => {               // pone una marca de 2 filas centrada sobre un glifo
  const c = Math.floor(w / 2) + (pos || 0), r = [Array(w).fill('.'), Array(w).fill('.')];
  if (kind === 'ac') { r[0][Math.min(w - 1, c + 1)] = '#'; r[1][c] = '#'; }
  if (kind === 'ti') { const x0 = Math.floor((w - 4) / 2); r[1][x0] = '#'; r[0][x0 + 1] = '#'; r[1][x0 + 2] = '#'; r[0][x0 + 3] = '#'; }
  if (kind === 'di') { r[1][Math.max(0, c - 1)] = '#'; r[1][Math.min(w - 1, c + 1)] = '#'; }
  return r.map(a => a.join(''));
};
